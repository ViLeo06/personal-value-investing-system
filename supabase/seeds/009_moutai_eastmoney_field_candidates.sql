begin;

insert into fundamentals.metric_definitions
    (metric_code, name_cn, name_en, statement_type, default_unit, description)
values
    ('revenue','营业收入','Revenue','income_statement','CNY','Consolidated operating revenue.'),
    ('net_income_parent','归母净利润','Net income attributable to parent','income_statement','CNY','Net income attributable to shareholders of the parent.'),
    ('operating_cash_flow','经营活动现金流净额','Net cash from operating activities','cash_flow','CNY','Net cash generated by operating activities.'),
    ('total_assets','总资产','Total assets','balance_sheet','CNY','Consolidated total assets.'),
    ('equity_parent','归母股东权益','Equity attributable to parent','balance_sheet','CNY','Equity attributable to shareholders of the parent.'),
    ('basic_eps','基本每股收益','Basic earnings per share','income_statement','CNY/share','Basic EPS reported for the period.')
on conflict (metric_code) do update
set name_cn=excluded.name_cn,
    name_en=excluded.name_en,
    statement_type=excluded.statement_type,
    default_unit=excluded.default_unit,
    description=excluded.description;

with source_row as (
    select source_id
    from raw.data_sources
    where source_code='AKSHARE_EASTMONEY_FINANCIAL'
), known(metric_code, dataset_code, statement_type, expected_value, unit) as (
    values
        ('revenue','eastmoney_income','income_statement',94915380916.72::numeric,'CNY'),
        ('net_income_parent','eastmoney_income','income_statement',46697285429.81::numeric,'CNY'),
        ('operating_cash_flow','eastmoney_cashflow','cash_flow',51669068693.03::numeric,'CNY'),
        ('total_assets','eastmoney_balance','balance_sheet',213395810527.46::numeric,'CNY'),
        ('equity_parent','eastmoney_balance','balance_sheet',161322735087.56::numeric,'CNY'),
        ('basic_eps','eastmoney_income','income_statement',37.17::numeric,'CNY/share')
), flattened as (
    select
        r.dataset_code,
        e.key as source_field,
        e.value as source_value
    from raw.records r
    join master.issuers i on i.issuer_id=r.issuer_id
    cross join lateral jsonb_each_text(r.payload) e
    where i.issuer_code='KWEICHOW_MOUTAI'
      and r.dataset_code like 'eastmoney_%'
      and e.value ~ '^-?[0-9]+(\.[0-9]+)?$'
), matched as (
    select distinct
        k.metric_code,
        k.dataset_code,
        k.statement_type,
        k.unit,
        f.source_field,
        f.source_value::numeric as matched_value,
        k.expected_value
    from known k
    join flattened f on f.dataset_code=k.dataset_code
    where abs(f.source_value::numeric-k.expected_value)
          <= greatest(abs(k.expected_value)*0.00000001,0.000001)
)
insert into fundamentals.source_metric_mappings
    (source_id,dataset_code,source_field,metric_code,statement_type,value_type,
     unit,scale,sign_multiplier,mapping_version,status,transform,notes)
select
    source_row.source_id,
    matched.dataset_code,
    matched.source_field,
    matched.metric_code,
    matched.statement_type,
    'numeric',
    matched.unit,
    1,
    1,
    'eastmoney-v1-auto-value-match',
    'candidate',
    jsonb_build_object(
        'match_method','exact_known_value',
        'expected_value',matched.expected_value,
        'matched_value',matched.matched_value
    ),
    'Automatically inferred from a value already validated against the annual report; field name still requires review.'
from matched
cross join source_row
on conflict (source_id,dataset_code,source_field,mapping_version) do nothing;

with candidates as (
    select
        r.dataset_code,
        e.key as source_field,
        e.value as source_value,
        row_number() over (
            partition by r.dataset_code
            order by e.key
        ) as ordinal
    from raw.records r
    join master.issuers i on i.issuer_id=r.issuer_id
    cross join lateral jsonb_each_text(r.payload) e
    where i.issuer_code='KWEICHOW_MOUTAI'
      and r.dataset_code like 'eastmoney_%'
      and e.key ~* '(DEPR|AMORT|CAPEX|CONSTRUCT|PURCHASE|FIXED|INTANG|MONETARY|CASH|LOAN|BORROW|BOND|DEBT|SHARE|CAPITAL|INVENTORY|RECEIV|PAYABLE|WORKING)'
), packed as (
    select jsonb_agg(
        jsonb_build_object(
            'dataset_code',dataset_code,
            'source_field',source_field,
            'source_value',source_value
        ) order by dataset_code,source_field
    ) as field_candidates
    from candidates
)
insert into audit.data_quality_issues
    (severity,domain,table_name,record_key,rule_code,description,status,details)
select
    'info',
    'field_mapping',
    'raw.records',
    'KWEICHOW_MOUTAI|2020|EASTMONEY_FIELDS',
    'SOURCE_FIELD_MAPPING_REVIEW_REQUIRED',
    'Candidate Eastmoney fields were identified for Owner Earnings, net cash, shares and working-capital mapping; official annual-report validation is required.',
    'open',
    jsonb_build_object(
        'source_code','AKSHARE_EASTMONEY_FINANCIAL',
        'mapping_version','eastmoney-v1-auto-value-match',
        'field_candidates',coalesce(packed.field_candidates,'[]'::jsonb),
        'formal_use_allowed',false
    )
from packed
where not exists (
    select 1 from audit.data_quality_issues existing
    where existing.rule_code='SOURCE_FIELD_MAPPING_REVIEW_REQUIRED'
      and existing.record_key='KWEICHOW_MOUTAI|2020|EASTMONEY_FIELDS'
      and existing.status='open'
);

commit;
