begin;

create table if not exists master.calendar_versions (
    calendar_version_id uuid primary key default gen_random_uuid(),
    exchange_mic text not null,
    calendar_version text not null,
    source_id uuid references raw.data_sources(source_id),
    source_document_id uuid references raw.documents(document_id),
    valid_from date not null,
    valid_to date,
    content_hash text not null,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (valid_to is null or valid_to >= valid_from),
    check (status <> 'frozen' or frozen_at is not null),
    unique (exchange_mic, calendar_version)
);

create table if not exists master.trading_day_versions (
    calendar_version_id uuid not null references master.calendar_versions(calendar_version_id) on delete cascade,
    trade_date date not null,
    is_open boolean not null,
    settlement_date date,
    source_note text,
    primary key (calendar_version_id, trade_date),
    check (settlement_date is null or settlement_date >= trade_date)
);

create table if not exists model.parameter_sets (
    parameter_set_id uuid primary key default gen_random_uuid(),
    issuer_id uuid references master.issuers(issuer_id),
    model_family text not null,
    parameter_version text not null,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    effective_from timestamptz not null,
    effective_to timestamptz,
    source_snapshot_id uuid references audit.data_snapshots(snapshot_id),
    content_hash text not null,
    notes text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (effective_to is null or effective_to >= effective_from),
    check (status <> 'frozen' or frozen_at is not null)
);

create unique index if not exists parameter_sets_identity_uq
    on model.parameter_sets (
        coalesce(issuer_id, '00000000-0000-0000-0000-000000000000'::uuid),
        model_family,
        parameter_version
    );

create table if not exists model.parameter_values (
    parameter_value_id bigint generated by default as identity primary key,
    parameter_set_id uuid not null references model.parameter_sets(parameter_set_id) on delete cascade,
    scenario text not null default 'base',
    parameter_key text not null,
    value_numeric numeric,
    value_text text,
    value_json jsonb,
    unit text,
    source_kind text not null default 'judgment',
    provenance jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    check (num_nonnulls(value_numeric, value_text, value_json) = 1),
    unique (parameter_set_id, scenario, parameter_key)
);

create table if not exists audit.quality_rule_sets (
    quality_rule_set_id uuid primary key default gen_random_uuid(),
    rule_set_version text not null unique,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    rules jsonb not null,
    content_hash text not null unique,
    notes text,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (status <> 'frozen' or frozen_at is not null)
);

create table if not exists audit.run_quality_results (
    quality_result_id bigint generated by default as identity primary key,
    run_type text not null,
    run_id uuid not null,
    quality_rule_set_id uuid not null references audit.quality_rule_sets(quality_rule_set_id),
    rule_code text not null,
    severity text not null check (severity in ('info','warning','error','critical')),
    passed boolean not null,
    details jsonb not null default '{}'::jsonb,
    checked_at timestamptz not null default now(),
    unique (run_type, run_id, quality_rule_set_id, rule_code)
);

create table if not exists audit.run_readiness (
    run_type text not null,
    run_id uuid not null,
    quality_rule_set_id uuid not null references audit.quality_rule_sets(quality_rule_set_id),
    readiness text not null check (readiness in ('validated','provisional','blocked')),
    summary jsonb not null default '{}'::jsonb,
    assessed_at timestamptz not null default now(),
    primary key (run_type, run_id, quality_rule_set_id)
);

create table if not exists audit.release_manifests (
    release_id uuid primary key default gen_random_uuid(),
    release_tag text not null unique,
    status text not null default 'draft'
        check (status in ('draft','frozen','retired')),
    git_commit_sha text not null,
    migration_versions jsonb not null,
    seed_versions jsonb not null,
    model_versions jsonb not null,
    parameter_set_ids uuid[] not null default '{}'::uuid[],
    data_snapshot_ids uuid[] not null default '{}'::uuid[],
    quality_rule_set_id uuid references audit.quality_rule_sets(quality_rule_set_id),
    dependency_manifest jsonb not null default '{}'::jsonb,
    environment_manifest jsonb not null default '{}'::jsonb,
    artifact_manifest jsonb not null default '{}'::jsonb,
    manifest_hash text not null unique,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (status <> 'frozen' or frozen_at is not null)
);

create index if not exists calendar_versions_source_idx
    on master.calendar_versions(source_id);
create index if not exists calendar_versions_document_idx
    on master.calendar_versions(source_document_id);
create index if not exists parameter_sets_issuer_idx
    on model.parameter_sets(issuer_id);
create index if not exists parameter_sets_snapshot_idx
    on model.parameter_sets(source_snapshot_id);
create index if not exists parameter_values_set_idx
    on model.parameter_values(parameter_set_id);
create index if not exists run_quality_results_run_idx
    on audit.run_quality_results(run_type, run_id);
create index if not exists release_manifests_quality_idx
    on audit.release_manifests(quality_rule_set_id);

revoke all on master.calendar_versions from anon, authenticated;
revoke all on master.trading_day_versions from anon, authenticated;
revoke all on model.parameter_sets from anon, authenticated;
revoke all on model.parameter_values from anon, authenticated;
revoke all on audit.quality_rule_sets from anon, authenticated;
revoke all on audit.run_quality_results from anon, authenticated;
revoke all on audit.run_readiness from anon, authenticated;
revoke all on audit.release_manifests from anon, authenticated;

commit;
