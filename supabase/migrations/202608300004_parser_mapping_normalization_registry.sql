begin;

create table if not exists raw.parser_versions (
    parser_version_id uuid primary key default gen_random_uuid(),
    parser_name text not null,
    semantic_version text not null,
    source_code text not null,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    code_git_sha text,
    config_hash text,
    notes text,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (status <> 'frozen' or frozen_at is not null),
    unique (parser_name, semantic_version)
);

create table if not exists raw.parser_runs (
    parser_run_id uuid primary key default gen_random_uuid(),
    document_id uuid not null references raw.documents(document_id),
    parser_version_id uuid not null references raw.parser_versions(parser_version_id),
    status text not null default 'queued'
        check (status in ('queued','running','completed','failed')),
    result_hash text,
    warnings jsonb not null default '[]'::jsonb,
    metadata jsonb not null default '{}'::jsonb,
    started_at timestamptz,
    completed_at timestamptz,
    error_text text,
    created_at timestamptz not null default now(),
    check (completed_at is null or started_at is null or completed_at >= started_at)
);

create unique index if not exists parser_runs_completed_identity_uq
    on raw.parser_runs(document_id, parser_version_id, result_hash)
    where result_hash is not null;

create table if not exists fundamentals.mapping_registries (
    mapping_registry_id uuid primary key default gen_random_uuid(),
    source_id uuid not null references raw.data_sources(source_id),
    mapping_version text not null,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    content_hash text not null,
    effective_from date,
    effective_to date,
    notes text,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (effective_to is null or effective_from is null or effective_to >= effective_from),
    check (status <> 'frozen' or frozen_at is not null),
    unique (source_id, mapping_version)
);

create table if not exists fundamentals.mapping_rules (
    mapping_rule_id bigint generated by default as identity primary key,
    mapping_registry_id uuid not null references fundamentals.mapping_registries(mapping_registry_id) on delete cascade,
    source_label text not null,
    normalized_label text not null,
    metric_code text not null references fundamentals.metric_definitions(metric_code),
    statement_type text not null,
    statement_scope text not null default 'consolidated',
    valid_from date,
    valid_to date,
    output_unit text,
    output_currency text,
    scale_multiplier numeric not null default 1 check (scale_multiplier > 0),
    sign_multiplier numeric not null default 1 check (sign_multiplier in (-1, 1)),
    priority integer not null default 100,
    notes text,
    created_at timestamptz not null default now(),
    check (valid_to is null or valid_from is null or valid_to >= valid_from)
);

create unique index if not exists mapping_rules_identity_uq
    on fundamentals.mapping_rules (
        mapping_registry_id,
        normalized_label,
        statement_type,
        statement_scope,
        coalesce(valid_from, date '0001-01-01'),
        coalesce(valid_to, date '9999-12-31'),
        priority,
        metric_code
    );

create table if not exists fundamentals.normalization_policies (
    normalization_policy_id uuid primary key default gen_random_uuid(),
    policy_code text not null,
    semantic_version text not null,
    model_family text,
    status text not null default 'development'
        check (status in ('development','frozen','retired')),
    configuration jsonb not null,
    content_hash text not null,
    notes text,
    created_at timestamptz not null default now(),
    frozen_at timestamptz,
    check (status <> 'frozen' or frozen_at is not null),
    unique (policy_code, semantic_version)
);

create table if not exists fundamentals.normalization_runs (
    normalization_run_id uuid primary key default gen_random_uuid(),
    issuer_id uuid not null references master.issuers(issuer_id),
    as_of_at timestamptz not null,
    snapshot_id uuid not null references audit.data_snapshots(snapshot_id),
    normalization_policy_id uuid not null references fundamentals.normalization_policies(normalization_policy_id),
    status text not null default 'queued'
        check (status in ('queued','running','completed','failed')),
    input_hash text,
    output_hash text,
    started_at timestamptz,
    completed_at timestamptz,
    error_text text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    check (completed_at is null or started_at is null or completed_at >= started_at)
);

create index if not exists parser_runs_document_idx
    on raw.parser_runs(document_id);
create index if not exists parser_runs_version_idx
    on raw.parser_runs(parser_version_id);
create index if not exists mapping_registries_source_idx
    on fundamentals.mapping_registries(source_id);
create index if not exists mapping_rules_registry_idx
    on fundamentals.mapping_rules(mapping_registry_id);
create index if not exists mapping_rules_metric_idx
    on fundamentals.mapping_rules(metric_code);
create index if not exists normalization_runs_issuer_asof_idx
    on fundamentals.normalization_runs(issuer_id, as_of_at);
create index if not exists normalization_runs_snapshot_idx
    on fundamentals.normalization_runs(snapshot_id);
create index if not exists normalization_runs_policy_idx
    on fundamentals.normalization_runs(normalization_policy_id);

revoke all on raw.parser_versions from anon, authenticated;
revoke all on raw.parser_runs from anon, authenticated;
revoke all on fundamentals.mapping_registries from anon, authenticated;
revoke all on fundamentals.mapping_rules from anon, authenticated;
revoke all on fundamentals.normalization_policies from anon, authenticated;
revoke all on fundamentals.normalization_runs from anon, authenticated;

commit;
